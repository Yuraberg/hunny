SYSTEM_PROMPT = """Выступай в роли эксперта-апиолога и биохимика. 
Твоя задача: написать подробную энциклопедическую статью для базы знаний Obsidian.

Формат: Markdown. Заголовок первого уровня — название темы.
Объём: 2000–2500 слов, максимально глубокое раскрытие темы.
Структура: детальный структурированный список (list) с вложенными пунктами, логические разделы.
Перекрёстные ссылки: используй [[Термин]] в двойных квадратных скобках на другие релевантные термины из пчеловодства (например, [[Мёд]], [[Перга]], [[Апитерапия]] и т.д.).
Язык: строгий научный, опирающийся на биохимию, физику и экологию процессов, без лишней «воды»."""


def clean_filename(title: str) -> str:
    return re.sub(r'[/\\?%*:|"<>]', '-', title)


def generate_article(topic: str) -> str:
    response = client.chat.completions.create(
        model=MODEL,
        messages=[
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": f"Напиши статью на тему: {topic}"},
        ],
        temperature=0.7,
        max_tokens=16384,
    )
    content = response.choices[0].message.content
    return f"# {topic}\n\n{content}"


def main():
    test_mode = "--test" in sys.argv
    output_dir = os.path.dirname(os.path.abspath(__file__))
    os.makedirs(output_dir, exist_ok=True)

    total = 1 if test_mode else len(TOPICS)
    topics_to_process = TOPICS[:1] if test_mode else TOPICS

    if test_mode:
        print(f"🧪 ТЕСТОВЫЙ РЕЖИМ — 1 статья: {TOPICS[0]}")
    else:
        print(f"🚀 ПОЛНЫЙ ЗАПУСК: {len(TOPICS)} статей в очереди")

    for i, topic in enumerate(topics_to_process, 1):
        file_name = f"{clean_filename(topic)}.md"
        file_path = os.path.join(output_dir, file_name)

        if os.path.exists(file_path) and not test_mode:
            print(f"[{i}/{total}] ⏭ пропуск: {file_name} уже существует")
            continue

        print(f"[{i}/{total}] ✍️ генерация: {topic} ...", flush=True)

        try:
            content = generate_article(topic)
            with open(file_path, "w", encoding="utf-8") as f:
                f.write(content)

            words = len(content.split())
            print(f"✅ [{i}/{total}] {file_name} ({words} слов)", flush=True)

            if not test_mode:
                time.sleep(3)  # пауза между запросами

        except Exception as e:
            print(f"❌ [{i}/{total}] ошибка {topic}: {e}", flush=True)
            if not test_mode:
                time.sleep(15)

    print("🏁 готово!")


if __name__ == "__main__":
    main()
